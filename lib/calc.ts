/**
 * 오피스 개발사업 사업성 계산 — 순수 함수만 둔다.
 *
 * 이 모듈은 React·브라우저 API·네트워크·현재시각·난수를 쓰지 않는다.
 * 같은 입력이면 항상 같은 결과가 나와야 `node --test` 로 검산할 수 있다.
 *
 * ── 단위 규칙 (이 앱 한정) ─────────────────────────────────────
 *   금액          : 억원          (예: 1200 = 1,200억원)
 *   면적          : 평 / ㎡       (공급면적은 평, 전용면적은 ㎡ 로 입력받는다)
 *   평당 월임대료 : 만원/평/월    (금액 중 유일한 예외)
 *   비율          : 백분율 숫자   (예: 30 = 30%, 4.5 = 4.5%)
 *
 * 프로젝트의 `src/lib` 는 분양형 수지(단위 만원)를 다루는 별도 앱이다.
 * 단위 체계가 다르므로 두 트리의 함수를 섞어 쓰지 말 것.
 */

/* ─── 상수 ─────────────────────────────────────────────────── */

/** 1평 = 400/121 ㎡. 반올림한 상수를 따로 만들지 말 것. */
export const 제곱미터_평 = 400 / 121;

/** 1억원 = 10,000만원 */
export const 만원_억원 = 10_000;

/**
 * 대손충당금율 1%.
 * 한국부동산원 순영업소득 산정 방식을 준용한 값으로, 입력값이 아니라
 * 계산 정의의 일부이므로 상수로 고정한다.
 */
export const 대손충당금율 = 0.01;

/* ─── 입력 타입 ────────────────────────────────────────────── */

/** 임대공간 구성표의 한 행 */
export interface 임대공간행 {
  /** 리스트 키 및 행 삭제용 식별자 */
  id: string;
  /** 구분명 (예: 기준층 오피스, 저층부 리테일) */
  구분명: string;
  /** 전용면적 (㎡) */
  전용면적m2: number;
  /** 임대(공급)면적 (평) */
  공급면적평: number;
  /** 해당 구분이 차지하는 층 수 (개 층) */
  층수: number;
}

/** 시장 기준치 수동 입력 — 공공데이터 연동 전까지의 입력원 */
export interface 시장기준치입력 {
  지역명: string;
  기준분기: string;
  /** 만원/평/월. 미확보 시 null */
  평당임대료: number | null;
  /** %. 미확보 시 null */
  공실률: number | null;
  /** % — 참고용 소득수익률. 미확보 시 null */
  소득수익률: number | null;
  출처명: string;
}

/** 사업계획서 입력 전체 */
export interface 사업계획입력 {
  사업명: string;
  /** 시도 (예: 서울특별시) */
  시도: string;
  /** 시군구 (예: 강남구, 성남시 분당구) */
  시군구: string;

  /** 임대공간 구성표 */
  임대공간: 임대공간행[];

  /** 평당 월임대료 — 공급면적 기준 (만원/평/월) */
  평당월임대료: number;
  /**
   * 운영경비율 (%).
   * 기본값 30 은 사용자가 지정한 가정치이며 공공데이터나 업계 자료로
   * 검증된 값이 아니다. 화면에는 반드시
   * "(가정치 — 근거 확인 필요, 조정 가능)"을 병기한다.
   */
  운영경비율: number;

  /** 상가(리테일) 연임대수입 (억원) */
  상가연임대수입: number;
  /** 기타유입 — 주차 등 (억원) */
  기타유입: number;
  /** 고정비 (억원) */
  고정비: number;

  /** 캡레이트 (%) — 시장 캡레이트 입력값 */
  캡레이트: number;
  /** 매각수수료율 (%) */
  매각수수료율: number;

  /** 본PF (억원) */
  본PF: number;
  /** 본PF 금융비용 — 총액 기준 (억원) */
  본PF금융비용: number;
  /** 후순위 (억원) */
  후순위: number;

  /** 시장 기준치 (수동 입력) */
  시장기준치: 시장기준치입력;
}

/* ─── 입력 방어 ────────────────────────────────────────────── */

/**
 * NaN·Infinity·비숫자를 대체값으로 바꾼다.
 * 방어는 계산 진입부에서 한 번만 하고 화면 컴포넌트가 떠안지 않게 한다.
 */
export function 수(값: unknown, 대체값 = 0): number {
  const n = typeof 값 === "number" ? 값 : Number(값);
  return Number.isFinite(n) ? n : 대체값;
}

/** 백분율 숫자를 배율로 바꾼다. 30 → 0.3 */
export function 배율(백분율: number): number {
  return 수(백분율) / 100;
}

/** ㎡ → 평 */
export function 제곱미터를평으로(m2: number): number {
  return 수(m2) / 제곱미터_평;
}

/* ─── 임대공간 구성표 집계 ─────────────────────────────────── */

/** 임대공간 구성표에서 뽑아낸 합계 */
export interface 임대공간집계 {
  /** 행 개수 */
  행수: number;
  /** 임대(공급)면적 합계 (평) */
  공급면적평합계: number;
  /** 전용면적 합계 (㎡) */
  전용면적m2합계: number;
  /** 전용면적 합계 (평) */
  전용면적평합계: number;
  /** 층수 합계 (개 층) */
  층수합계: number;
  /** 전용률 (%) = 전용면적 ÷ 공급면적. 공급면적이 0 이면 null */
  전용률: number | null;
}

/**
 * 임대공간 구성표를 합산한다.
 * 전용률은 분모가 0 일 때 0% 가 아니라 null 을 돌려준다 —
 * "전용률 0%" 는 근거 없는 확정 사실이 되기 때문이다.
 */
export function 임대공간집계하기(행목록: 임대공간행[]): 임대공간집계 {
  let 공급면적평합계 = 0;
  let 전용면적m2합계 = 0;
  let 층수합계 = 0;

  for (const 행 of 행목록) {
    공급면적평합계 += Math.max(0, 수(행.공급면적평));
    전용면적m2합계 += Math.max(0, 수(행.전용면적m2));
    층수합계 += Math.max(0, 수(행.층수));
  }

  const 전용면적평합계 = 제곱미터를평으로(전용면적m2합계);

  return {
    행수: 행목록.length,
    공급면적평합계,
    전용면적m2합계,
    전용면적평합계,
    층수합계,
    전용률: 공급면적평합계 > 0 ? (전용면적평합계 / 공급면적평합계) * 100 : null,
  };
}

/* ─── 수익 · NOI ───────────────────────────────────────────── */

/**
 * 연임대수입(GPI, 억원).
 *
 *   GPI = (임대면적(평) × 평당월임대료(만원) × 12 ÷ 10,000 + 상가연임대수입) × 임대율
 *
 * ÷10,000 은 만원을 억원으로 바꾸는 환산이다.
 * 임대율은 오피스 임대수입과 상가 임대수입에 함께 적용한다(사양 정의).
 */
export function 연임대수입계산(
  임대면적평: number,
  평당월임대료: number,
  상가연임대수입: number,
  임대율: number,
): number {
  const 오피스연임대수입 =
    (Math.max(0, 수(임대면적평)) * Math.max(0, 수(평당월임대료)) * 12) / 만원_억원;
  return (오피스연임대수입 + 수(상가연임대수입)) * Math.max(0, 수(임대율));
}

/** NOI 산정 중간값까지 담은 결과 (단위 억원) */
export interface NOI결과 {
  /** 연임대수입 */
  임대수입: number;
  /** 기타수입 */
  기타수입: number;
  /** 대손충당금 = (임대수입 + 기타수입) × 1% */
  대손충당금: number;
  /** 유효조소득 = 임대수입 + 기타수입 − 대손충당금 */
  유효조소득: number;
  /** 운영경비 = 유효조소득 × 운영경비율 */
  운영경비: number;
  /** 고정비 */
  고정비: number;
  /** NOI = 유효조소득 × (1 − 운영경비율) − 고정비 */
  NOI: number;
}

/**
 * NOI 를 계산한다 — 한국부동산원 순영업소득 정의를 준용.
 *
 *   대손충당금 = (임대수입 + 기타수입) × 1%
 *   유효조소득 = 임대수입 + 기타수입 − 대손충당금
 *   NOI       = 유효조소득 × (1 − 운영경비율) − 고정비
 *
 * 운영경비율은 사용자 가정치다. 검증된 시장 수치가 아니므로 화면에서
 * "(가정치)" 표기를 반드시 병기해야 한다.
 */
export function NOI계산(
  임대수입: number,
  기타수입: number,
  운영경비율: number,
  고정비: number,
): NOI결과 {
  const 임대 = 수(임대수입);
  const 기타 = 수(기타수입);
  const 조소득 = 임대 + 기타;
  const 대손충당금 = 조소득 * 대손충당금율;
  const 유효조소득 = 조소득 - 대손충당금;
  const 운영경비 = 유효조소득 * 배율(운영경비율);
  const 고정 = 수(고정비);

  return {
    임대수입: 임대,
    기타수입: 기타,
    대손충당금,
    유효조소득,
    운영경비,
    고정비: 고정,
    NOI: 유효조소득 - 운영경비 - 고정,
  };
}

/* ─── 자산가치 · 매각 · 상환 ───────────────────────────────── */

/**
 * 자산가치 (억원) = NOI ÷ 캡레이트.
 * 캡레이트가 0 이하이면 나눗셈이 성립하지 않으므로 null 을 돌려준다.
 * (0 이나 Infinity 를 돌려주면 조용히 이상한 숫자가 표에 실린다)
 */
export function 자산가치계산(NOI: number, 캡레이트: number): number | null {
  const c = 배율(캡레이트);
  if (c <= 0) return null;
  return 수(NOI) / c;
}

/** 매각정산액 (억원) = 자산가치 × (1 − 매각수수료율) */
export function 매각정산액계산(
  자산가치: number | null,
  매각수수료율: number,
): number | null {
  if (자산가치 === null) return null;
  return 자산가치 * (1 - 배율(매각수수료율));
}

/**
 * 만기 누적 DSCR = 1 + (본PF 상환 후 잔액 + 후순위) ÷ (본PF + 본PF 금융비용)
 *
 * 사양의 "매각정산액"은 본PF 상환 후 잔액을 가리킨다(사용자 확정).
 * 이 정의를 넣고 정리하면 관습적인 상환능력 비율과 정확히 같아진다.
 *
 *   1 + (매각총액 − (본PF + 비용) + 후순위) ÷ (본PF + 비용)
 *     = (매각총액 + 후순위) ÷ (본PF + 비용)
 *     = 상환재원 ÷ 상환의무
 *
 * 따라서 DSCR ≥ 1 은 "손실이 후순위 한도 안에서 흡수된다"와 같은 말이다.
 * 상환 전 총액을 넣으면 DSCR 이 항상 1 을 넘어 판정 기능을 잃는다.
 *
 * 본PF + 금융비용이 0 이면 분모가 0 이므로 null 을 돌려준다.
 */
export function 만기누적DSCR계산(
  본PF상환후잔액: number | null,
  후순위: number,
  본PF: number,
  본PF금융비용: number,
): number | null {
  if (본PF상환후잔액 === null) return null;
  const 상환의무 = 수(본PF) + 수(본PF금융비용);
  if (상환의무 <= 0) return null;
  return 1 + (본PF상환후잔액 + 수(후순위)) / 상환의무;
}

/**
 * 본PF 상환 후 잔액 (억원) = 매각정산액 − (본PF + 본PF 금융비용)
 *
 * 한계선 판정에 쓰는 값이다.
 *   잔액 = 0        → 본PF 원리금을 정확히 상환하는 한계선
 *   잔액 = −후순위  → 손실이 후순위 한도까지 흡수되는 한계선
 * 잔액이 −후순위보다 작아지면 선순위 손실이 발생한다.
 */
export function 본PF상환후잔액계산(
  매각정산액: number | null,
  본PF: number,
  본PF금융비용: number,
): number | null {
  if (매각정산액 === null) return null;
  return 매각정산액 - (수(본PF) + 수(본PF금융비용));
}

/**
 * LTV (%) = 본PF ÷ 자산가치.
 * 자산가치는 완전임대(임대율 100%) 기준으로 계산한다 — 대주단 심사에서 쓰는
 * LTV 는 안정화 이후 가치를 분모로 보기 때문이다.
 */
export function LTV계산(
  본PF: number,
  완전임대자산가치: number | null,
): number | null {
  if (완전임대자산가치 === null || 완전임대자산가치 <= 0) return null;
  return (수(본PF) / 완전임대자산가치) * 100;
}

/* ─── 전체 계산 ────────────────────────────────────────────── */

/** 특정 임대율에서의 사업성 계산 결과 */
export interface 사업성결과 {
  /** 적용한 임대율 (배율. 1 = 100%) */
  임대율: number;
  /** 임대(공급)면적 합계 (평) */
  임대면적평: number;
  noi: NOI결과;
  자산가치: number | null;
  매각정산액: number | null;
  본PF상환후잔액: number | null;
  만기누적DSCR: number | null;
  /** 완전임대 기준 LTV (%) */
  LTV: number | null;
  /** 본PF 원리금을 상환할 수 있는가 (잔액 ≥ 0) */
  본PF상환가능: boolean;
  /** 손실이 후순위 한도 안에서 흡수되는가 (잔액 ≥ −후순위) */
  후순위내흡수: boolean;
}

/**
 * 입력과 임대율로 사업성 전체를 계산한다.
 * 임대율은 0.75, 1 처럼 배율로 넘긴다(백분율 아님).
 */
export function 사업성계산(입력: 사업계획입력, 임대율: number): 사업성결과 {
  const 집계 = 임대공간집계하기(입력.임대공간);
  const r = Math.max(0, 수(임대율));

  const 임대수입 = 연임대수입계산(
    집계.공급면적평합계,
    입력.평당월임대료,
    입력.상가연임대수입,
    r,
  );
  const noi = NOI계산(임대수입, 입력.기타유입, 입력.운영경비율, 입력.고정비);

  const 자산가치 = 자산가치계산(noi.NOI, 입력.캡레이트);
  const 매각정산액 = 매각정산액계산(자산가치, 입력.매각수수료율);
  const 잔액 = 본PF상환후잔액계산(매각정산액, 입력.본PF, 입력.본PF금융비용);

  // LTV 는 완전임대(r = 1) 기준 자산가치를 분모로 쓴다.
  const 완전임대NOI = NOI계산(
    연임대수입계산(
      집계.공급면적평합계,
      입력.평당월임대료,
      입력.상가연임대수입,
      1,
    ),
    입력.기타유입,
    입력.운영경비율,
    입력.고정비,
  ).NOI;

  return {
    임대율: r,
    임대면적평: 집계.공급면적평합계,
    noi,
    자산가치,
    매각정산액,
    본PF상환후잔액: 잔액,
    만기누적DSCR: 만기누적DSCR계산(
      잔액,
      입력.후순위,
      입력.본PF,
      입력.본PF금융비용,
    ),
    LTV: LTV계산(입력.본PF, 자산가치계산(완전임대NOI, 입력.캡레이트)),
    본PF상환가능: 잔액 !== null && 잔액 >= 0,
    후순위내흡수: 잔액 !== null && 잔액 >= -수(입력.후순위),
  };
}

/* ─── 한계선 (이분법) ──────────────────────────────────────── */

/** 한계선을 어느 수준으로 잡을지 */
export type 한계선기준 =
  /** 본PF 원리금 전액 상환 (잔액 = 0) */
  | "본PF상환"
  /** 손실이 후순위 한도까지 흡수 (잔액 = −후순위) */
  | "후순위흡수";

/** 이분법 결과 */
export interface 한계선결과 {
  /** 해. 탐색 구간 안에 없으면 null */
  값: number | null;
  /** 해에서의 잔차. 0 에 수렴해야 한다 */
  잔차: number;
  /** 반복 횟수 */
  반복: number;
}

/**
 * f(x) = 0 의 해를 이분법으로 찾는다.
 *
 * 종료 조건을 구간 폭의 절대값으로 끊으면 f 의 기울기가 클 때 잔차가 크게
 * 남는다(캡레이트 0.01%p 차이가 수십억을 움직인다). 기계 정밀도까지 좁힌다.
 * f 가 증가함수든 감소함수든 동작한다.
 */
export function 이분법(
  f: (x: number) => number,
  하한: number,
  상한: number,
  잔차허용치 = 1e-9,
  최대반복 = 200,
): 한계선결과 {
  let flo = f(하한);
  const fhi = f(상한);

  if (!Number.isFinite(flo) || !Number.isFinite(fhi)) {
    return { 값: null, 잔차: Number.NaN, 반복: 0 };
  }
  if (flo === 0) return { 값: 하한, 잔차: 0, 반복: 0 };
  if (fhi === 0) return { 값: 상한, 잔차: 0, 반복: 0 };
  // 양끝의 부호가 같으면 구간 안에 해가 없다.
  if (flo > 0 === fhi > 0) return { 값: null, 잔차: Number.NaN, 반복: 0 };

  let a = 하한;
  let b = 상한;
  let 중간 = (a + b) / 2;
  let f중간 = f(중간);
  let i = 0;

  for (; i < 최대반복; i++) {
    중간 = (a + b) / 2;
    f중간 = f(중간);
    const x해상도 = Math.max(Number.EPSILON * Math.abs(중간), 1e-15);
    if (Math.abs(f중간) <= 잔차허용치 || b - a <= x해상도) break;
    if (f중간 > 0 === flo > 0) {
      a = 중간;
      flo = f중간;
    } else {
      b = 중간;
    }
  }

  return { 값: 중간, 잔차: f중간, 반복: i };
}

/** 한계선 기준에 해당하는 목표 잔액 (억원) */
function 목표잔액(입력: 사업계획입력, 기준: 한계선기준): number {
  return 기준 === "본PF상환" ? 0 : -수(입력.후순위);
}

/**
 * 한계 임대율 (%). 이 아래로 떨어지면 목표 잔액을 못 맞춘다.
 * 임대율 0~200% 구간에서 찾는다.
 */
export function 한계임대율(
  입력: 사업계획입력,
  기준: 한계선기준 = "본PF상환",
): 한계선결과 {
  const 목표 = 목표잔액(입력, 기준);
  return 이분법(
    (r) => (사업성계산(입력, r / 100).본PF상환후잔액 ?? Number.NaN) - 목표,
    0,
    200,
  );
}

/**
 * 한계 평당 월임대료 (만원/평/월).
 * 현재 입력값의 5배까지를 탐색 구간으로 잡는다.
 */
export function 한계평당월임대료(
  입력: 사업계획입력,
  기준: 한계선기준 = "본PF상환",
  임대율 = 1,
): 한계선결과 {
  const 목표 = 목표잔액(입력, 기준);
  const 상한 = Math.max(1, 수(입력.평당월임대료)) * 5;
  return 이분법(
    (p) =>
      (사업성계산({ ...입력, 평당월임대료: p }, 임대율).본PF상환후잔액 ??
        Number.NaN) - 목표,
    0,
    상한,
  );
}

/**
 * 한계 캡레이트 (%). 이 위로 올라가면 목표 잔액을 못 맞춘다.
 * 자산가치 = NOI ÷ c 이므로 c 에 대해 감소함수다.
 * c = 0 에서 발산하므로 0.01% 부터 탐색한다.
 */
export function 한계캡레이트(
  입력: 사업계획입력,
  기준: 한계선기준 = "본PF상환",
  임대율 = 1,
): 한계선결과 {
  const 목표 = 목표잔액(입력, 기준);
  return 이분법(
    (c) =>
      (사업성계산({ ...입력, 캡레이트: c }, 임대율).본PF상환후잔액 ??
        Number.NaN) - 목표,
    0.01,
    30,
  );
}

/**
 * 캡레이트가 변동폭(%p) 만큼 움직일 때 자산가치 변화율 (%).
 *
 *   자산가치 = NOI ÷ c 이므로  변화율 = (c ÷ (c + Δ)) − 1 = −Δ ÷ (c + Δ)
 *
 * c 가 작을수록 같은 %p 변동의 충격이 커진다는 점을 이 식이 그대로 보여준다.
 * 캡레이트가 0 이하가 되면 성립하지 않으므로 null.
 */
export function 캡레이트변동_자산가치변화율(
  캡레이트: number,
  변동폭: number,
): number | null {
  const c = 수(캡레이트);
  const 변동후 = c + 수(변동폭);
  if (c <= 0 || 변동후 <= 0) return null;
  return (-수(변동폭) / 변동후) * 100;
}

/* ─── 민감도 ───────────────────────────────────────────────── */

/**
 * 민감도 표의 한 칸.
 * 셀 값은 본PF 상환 후 잔액(억원)이다 — 이 값의 부호가 상환 가능/불가를 가른다.
 */
export interface 민감도셀 {
  /** 행 값 — 임대율 (%) */
  임대율: number;
  /** 열 값 — 캡레이트(%) 또는 평당 월임대료(만원/평·월) */
  열값: number;
  /** 본PF 상환 후 잔액 (억원). 캡레이트가 0 이하면 null */
  잔액: number | null;
  /** 만기 누적 DSCR */
  DSCR: number | null;
  /** 잔액 ≥ 0 */
  본PF상환가능: boolean;
  /** 잔액 ≥ −후순위 (손실이 후순위 한도 안에서 흡수됨) */
  후순위내흡수: boolean;
}

/** 민감도 표 */
export interface 민감도표 {
  /** 행 값 목록 — 임대율 (%) */
  행: number[];
  /** 열 값 목록 */
  열: number[];
  /** 셀[행 인덱스][열 인덱스] */
  셀: 민감도셀[][];
}

/** 임대율 행 기본 구간 — 75~100%, 5%p 단위 */
export const 기본임대율구간 = [75, 80, 85, 90, 95, 100];

/**
 * 캡레이트 열 기본 변동폭 — 시장 캡레이트 대비 −1.0%p ~ +1.0%p, 0.25%p 단위.
 *
 * [확인 필요] 이 구간은 임의로 잡은 값이다. 실제 최근 분기 캡레이트 변동폭
 * (분기당 0.2%p 내외 변동 사례 등)을 확인해 구간을 다시 정할지 검토가 필요하다.
 */
export const 기본캡레이트변동구간 = [
  -1, -0.75, -0.5, -0.25, 0, 0.25, 0.5, 0.75, 1,
];

/** 한 칸을 계산한다 */
function 셀만들기(
  입력: 사업계획입력,
  임대율백분율: number,
  열값: number,
): 민감도셀 {
  const 결과 = 사업성계산(입력, 임대율백분율 / 100);
  return {
    임대율: 임대율백분율,
    열값,
    잔액: 결과.본PF상환후잔액,
    DSCR: 결과.만기누적DSCR,
    본PF상환가능: 결과.본PF상환가능,
    후순위내흡수: 결과.후순위내흡수,
  };
}

/**
 * 캡레이트 민감도 표.
 * 행 = 임대율, 열 = 시장 캡레이트에 변동폭(%p)을 더한 캡레이트.
 */
export function 캡레이트민감도표(
  입력: 사업계획입력,
  변동구간: number[] = 기본캡레이트변동구간,
  임대율구간: number[] = 기본임대율구간,
): 민감도표 {
  const 열 = 변동구간.map((변동) => 수(입력.캡레이트) + 변동);
  return {
    행: 임대율구간,
    열,
    셀: 임대율구간.map((r) =>
      열.map((c) => 셀만들기({ ...입력, 캡레이트: c }, r, c)),
    ),
  };
}

/** 평당 월임대료 열의 단차를 어떻게 잡을지 */
export type 임대료단차방식 =
  /** 기준값의 ±비율 (예: 10% 씩) */
  | "비율"
  /** 기준값에서 ±고정 금액 (만원) */
  | "금액";

/**
 * 평당 월임대료 열 목록을 만든다.
 *
 * [확인 필요] 단차를 기준값의 ±비율로 잡을지 고정 금액으로 잡을지는 아직
 * 정해지지 않았다. 그래서 한쪽을 코드에 박지 않고 방식과 폭을 인자로 받는다.
 *
 * @param 기준 가운데 열에 놓을 평당 월임대료 (만원/평·월)
 * @param 방식 "비율" 이면 폭을 %로, "금액" 이면 폭을 만원으로 해석한다
 * @param 폭   한 칸의 단차
 * @param 구간수 가운데를 기준으로 좌우 각각 몇 칸을 둘지
 */
export function 임대료열만들기(
  기준: number,
  방식: 임대료단차방식 = "비율",
  폭 = 10,
  구간수 = 2,
): number[] {
  const 중심 = Math.max(0, 수(기준));
  const 칸수 = Math.max(0, Math.trunc(수(구간수)));
  const 열: number[] = [];
  for (let k = -칸수; k <= 칸수; k++) {
    const 값 =
      방식 === "비율" ? 중심 * (1 + (k * 수(폭)) / 100) : 중심 + k * 수(폭);
    열.push(Math.max(0, 값));
  }
  return 열;
}

/**
 * 임대율 · 평당 월임대료 민감도 표.
 * 행 = 임대율, 열 = 평당 월임대료.
 */
export function 임대료민감도표(
  입력: 사업계획입력,
  임대료열: number[],
  임대율구간: number[] = 기본임대율구간,
): 민감도표 {
  return {
    행: 임대율구간,
    열: 임대료열,
    셀: 임대율구간.map((r) =>
      임대료열.map((p) => 셀만들기({ ...입력, 평당월임대료: p }, r, p)),
    ),
  };
}
