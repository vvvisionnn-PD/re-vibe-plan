describe("NOI — 한국부동산원 정의 준용", () => {
  const r = NOI계산(100, 20, 30, 5);

  it("대손충당금 = (임대수입 + 기타수입) × 1%", () => {
    assert.equal(대손충당금율, 0.01);
    근사(r.대손충당금, (100 + 20) * 0.01);
  });

  it("유효조소득 = 임대수입 + 기타수입 − 대손충당금", () => {
    근사(r.유효조소득, r.임대수입 + r.기타수입 - r.대손충당금);
  });

  it("운영경비 = 유효조소득 × 운영경비율", () => {
    근사(r.운영경비, r.유효조소득 * 배율(30));
  });

  it("NOI = 유효조소득 × (1 − 운영경비율) − 고정비", () => {
    근사(r.NOI, r.유효조소득 * (1 - 배율(30)) - r.고정비);
    근사(r.NOI, r.유효조소득 - r.운영경비 - r.고정비);
  });

  it("운영경비율 0% 이면 NOI = 유효조소득 − 고정비", () => {
    const r0 = NOI계산(100, 20, 0, 5);
    근사(r0.NOI, r0.유효조소득 - 5);
  });

  it("운영경비율이 오르면 NOI 가 줄어든다", () => {
    assert.ok(NOI계산(100, 20, 40, 5).NOI < NOI계산(100, 20, 30, 5).NOI);
  });

  it("고정비가 오르면 NOI 가 같은 폭으로 줄어든다", () => {
    근사(NOI계산(100, 20, 30, 15).NOI, NOI계산(100, 20, 30, 5).NOI - 10);
  });
});

