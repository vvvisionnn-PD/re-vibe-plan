/** 상대오차 기준 근사 비교. 금액 규모가 커도 안정적이다. */
function 근사(실제: number, 기대: number, 상대오차 = 1e-9) {
  const 허용 = Math.max(1e-9, Math.abs(기대) * 상대오차);
  assert.ok(
    Math.abs(실제 - 기대) <= 허용,
    `기대 ${기대}, 실제 ${실제}, 차이 ${Math.abs(실제 - 기대)} > 허용 ${허용}`,
  );
}

