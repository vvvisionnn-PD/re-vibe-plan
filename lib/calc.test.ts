describe("캡레이트 민감도 표", () => {
  const 표 = 캡레이트민감도표(픽스처);

  it("행·열 크기가 구간 배열과 일치한다", () => {
    assert.equal(표.행.length, 기본임대율구간.length);
    assert.equal(표.열.length, 기본캡레이트변동구간.length);
    for (const 행 of 표.셀) assert.equal(행.length, 표.열.length);
  });

  it("열 값 = 시장 캡레이트 + 변동폭", () => {
    표.열.forEach((c, i) => {
      근사(c, 픽스처.캡레이트 + 기본캡레이트변동구간[i]);
    });
  });

  it("변동 0 · 임대율 100% 칸이 기준 시나리오와 같다", () => {
    const 행 = 표.행.indexOf(100);
    const 열 = 기본캡레이트변동구간.indexOf(0);
    const 기준 = 사업성계산(픽스처, 1);
    근사(표.셀[행][열].잔액!, 기준.본PF상환후잔액!);
    근사(표.셀[행][열].DSCR!, 기준.만기누적DSCR!);
  });

  it("한 행 안에서 캡레이트가 오를수록 잔액이 줄어든다", () => {
    for (const 행 of 표.셀) {
      for (let i = 1; i < 행.length; i++) {
        assert.ok(
          행[i].잔액! < 행[i - 1].잔액!,
          `캡레이트 ${행[i].열값}% 에서 잔액이 줄지 않았다`,
        );
      }
    }
  });

  it("한 열 안에서 임대율이 오를수록 잔액이 늘어난다", () => {
    for (let 열 = 0; 열 < 표.열.length; 열++) {
      for (let 행 = 1; 행 < 표.셀.length; 행++) {
        assert.ok(표.셀[행][열].잔액! > 표.셀[행 - 1][열].잔액!);
      }
    }
  });

  it("셀의 판정 플래그가 잔액 부호와 일관된다", () => {
    for (const 행 of 표.셀) {
      for (const 칸 of 행) {
        assert.equal(칸.본PF상환가능, 칸.잔액! >= 0);
        assert.equal(칸.후순위내흡수, 칸.잔액! >= -픽스처.후순위);
      }
    }
  });

  it("색이 바뀌는 경계가 한계 캡레이트와 맞물린다", () => {
    const 한계 = 한계캡레이트(픽스처, "본PF상환").값!;
    const 조금아래 = 사업성계산({ ...픽스처, 캡레이트: 한계 - 0.01 }, 1);
    const 조금위 = 사업성계산({ ...픽스처, 캡레이트: 한계 + 0.01 }, 1);
    assert.equal(조금아래.본PF상환가능, true);
    assert.equal(조금위.본PF상환가능, false);
  });

  it("사용자 지정 구간을 그대로 쓴다", () => {
    const 좁은표 = 캡레이트민감도표(픽스처, [-0.2, 0, 0.2], [90, 100]);
    assert.equal(좁은표.행.length, 2);
    assert.equal(좁은표.열.length, 3);
    근사(좁은표.열[2], 픽스처.캡레이트 + 0.2);
  });
});

