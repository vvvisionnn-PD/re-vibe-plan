describe("사업성계산 — 결과 사이의 항등식", () => {
  const 결과 = 사업성계산(픽스처, 1);

  it("NOI 결과가 개별 함수와 같다", () => {
    const 집계 = 임대공간집계하기(픽스처.임대공간);
    const 기대 = NOI계산(
      연임대수입계산(
        집계.공급면적평합계,
        픽스처.평당월임대료,
        픽스처.상가연임대수입,
        1,
      ),
      픽스처.기타유입,
      픽스처.운영경비율,
      픽스처.고정비,
    );
    근사(결과.noi.NOI, 기대.NOI);
  });

  it("자산가치 · 매각정산액 · 잔액이 서로 맞물린다", () => {
    근사(결과.자산가치!, 결과.noi.NOI / 배율(픽스처.캡레이트));
    근사(결과.매각정산액!, 결과.자산가치! * (1 - 배율(픽스처.매각수수료율)));
    근사(
      결과.본PF상환후잔액!,
      결과.매각정산액! - (픽스처.본PF + 픽스처.본PF금융비용),
    );
  });

  it("만기 누적 DSCR = 1 + (본PF 상환 후 잔액 + 후순위) ÷ (본PF + 금융비용)", () => {
    근사(
      결과.만기누적DSCR!,
      1 +
        (결과.본PF상환후잔액! + 픽스처.후순위) /
          (픽스처.본PF + 픽스처.본PF금융비용),
    );
  });

  it("정리하면 상환재원 ÷ 상환의무 와 같다", () => {
    // 1 + (매각총액 − (본PF + 비용) + 후순위) ÷ (본PF + 비용)
    //   = (매각총액 + 후순위) ÷ (본PF + 비용)
    근사(
      결과.만기누적DSCR!,
      (결과.매각정산액! + 픽스처.후순위) /
        (픽스처.본PF + 픽스처.본PF금융비용),
    );
  });

  it("DSCR ≥ 1 과 후순위내흡수가 같은 판정이다", () => {
    for (const r of [0.2, 0.4, 0.6, 0.8, 1]) {
      const x = 사업성계산(픽스처, r);
      assert.equal(
        x.만기누적DSCR! >= 1,
        x.후순위내흡수,
        `임대율 ${r} 에서 DSCR ${x.만기누적DSCR} 과 후순위내흡수 ${x.후순위내흡수} 가 어긋난다`,
      );
    }
  });

  it("상환 전 총액을 쓰면 판정 기능을 잃는다 (정정 전 정의 회귀 방지)", () => {
    // 매각정산액(상환 전 총액)으로 계산하면 언제나 1 을 넘어 버린다.
    const 잘못된정의 =
      1 +
      (결과.매각정산액! + 픽스처.후순위) /
        (픽스처.본PF + 픽스처.본PF금융비용);
    assert.ok(잘못된정의 > 1);
    assert.notEqual(결과.만기누적DSCR, 잘못된정의);
  });

  it("상환 판정 플래그가 잔액과 일관된다", () => {
    assert.equal(결과.본PF상환가능, 결과.본PF상환후잔액! >= 0);
    assert.equal(결과.후순위내흡수, 결과.본PF상환후잔액! >= -픽스처.후순위);
  });

  it("LTV 는 임대율과 무관하다 (완전임대 기준이므로)", () => {
    근사(사업성계산(픽스처, 0.75).LTV!, 사업성계산(픽스처, 1).LTV!);
  });

  it("임대율이 오르면 잔액이 커진다", () => {
    assert.ok(
      사업성계산(픽스처, 1).본PF상환후잔액! >
        사업성계산(픽스처, 0.8).본PF상환후잔액!,
    );
  });

  it("캡레이트가 오르면 잔액이 작아진다", () => {
    assert.ok(
      사업성계산({ ...픽스처, 캡레이트: 6 }, 1).본PF상환후잔액! <
        사업성계산(픽스처, 1).본PF상환후잔액!,
    );
  });

  it("입력 객체를 변형하지 않는다", () => {
    const 스냅샷 = JSON.stringify(픽스처);
    사업성계산(픽스처, 0.9);
    assert.equal(JSON.stringify(픽스처), 스냅샷);
  });

  it("같은 입력이면 항상 같은 결과다", () => {
    assert.deepEqual(사업성계산(픽스처, 0.9), 사업성계산(픽스처, 0.9));
  });
});

