/** 사업계획 쪽에서 비교에 쓰는 값들을 한 번에 뽑는다 */
function 계획값들(입력: 사업계획입력) {
  const 결과 = 사업성계산(입력, 1);
  const 공급면적평 = 결과.임대면적평;
  return {
    결과,
    공급면적평,
    평당월임대료: 수(입력.평당월임대료),
    // 사업수지는 임대율 100%(완전임대)를 기준으로 잡는다 → 계획 공실률 0%
    계획공실률: 0,
    NOI억원: 결과.noi.NOI,
    캡레이트: 수(입력.캡레이트),
    자산가치억원: 결과.자산가치,
  };
}

/**
 * 시장 임대료를 앱의 단위(만원/평·월)로 맞춘다.
 *
 * R-ONE 오피스 임대료는 "천원/㎡" 로 공표된다(실제 응답에서 확인).
 *   X 천원/㎡ = X × 1,000 원/㎡ = X × 1,000 × (400/121) 원/평
 *             = X × (400/121) ÷ 10  만원/평
 *
 * 아는 단위만 환산하고, 모르는 단위는 null 을 돌려 단위불일치로 처리한다.
 * 추측해서 환산하면 근거 없는 숫자가 표에 실린다.
 */
export function 임대료를만원평으로(
  값: number | null,
  단위: string,
): { 값: number | null; 환산됨: boolean; 원단위: string } {
  if (값 === null) return { 값: null, 환산됨: false, 원단위: 단위 };
  // 공백만 지운다. 정규식 이스케이프는 조립 과정에서 뭉개지기 쉬워 쓰지 않는다.
  const u = 단위.split(" ").join("");
  if (u.includes("만원") && u.includes("평")) {
    return { 값, 환산됨: false, 원단위: 단위 };
  }
  if (u.includes("천원") && (u.includes("㎡") || u.includes("m2"))) {
    return { 값: (값 * 제곱미터_평) / 10, 환산됨: true, 원단위: 단위 };
  }
  return { 값: null, 환산됨: false, 원단위: 단위 };
}

/** 1) 인근 오피스 평당임대료 vs 계획 평당임대료 */
export function 임대료비교표(
  입력: 사업계획입력,
  지표: 시장지표응답 | null,
  강조임계 = 기본강조임계,
): 비교행 {
  const 계획 = 계획값들(입력);
  const 환산 = 임대료를만원평으로(지표?.값 ?? null, 지표?.단위 ?? "");
  const 환산실패 = (지표?.값 ?? null) !== null && 환산.값 === null;

  return 비교행만들기({
    항목: "평당 월임대료 (공급 기준)",
    시장값: 환산실패 ? (지표?.값 ?? null) : 환산.값,
    시장라벨: 환산실패 ? 환산.원단위 : "만원/평·월",
    계획값: 계획.평당월임대료 > 0 ? 계획.평당월임대료 : null,
    계획라벨: "만원/평·월",
    단위: 환산실패 ? "" : "만원/평·월",
    강조임계,
    단위불일치: 환산실패,
    문장꼬리: 환산.환산됨
      ? `시장 자료는 ${환산.원단위} 로 공표된다 — 만원/평·월 로 환산해 견줬다.`
      : 환산실패
        ? `[확인 필요] 시장 자료의 단위 "${환산.원단위}" 에 대한 환산 규칙이 없다.`
        : "",
  });
}

/** 2) 인근 오피스 공실률 vs 계획 임대율 가정 */
export function 공실률비교표(
  입력: 사업계획입력,
  지표: 시장지표응답 | null,
  강조임계 = 기본강조임계,
): 비교행 {
  const 계획 = 계획값들(입력);
  const 한계 = 한계임대율(입력, "본PF상환").값;
  return 비교행만들기({
    항목: "공실률",
    시장값: 지표?.값 ?? null,
    시장라벨: 지표?.단위 || "%",
    계획값: 계획.계획공실률,
    계획라벨: "%",
    단위: "%",
    // 계획이 완전임대(공실률 0%)라 시장 공실률이 조금만 있어도 괴리율이 커진다.
    // 비율이 아니라 절대 %p 로 강조 여부를 따로 판단한다.
    강조임계,
    문장꼬리:
      한계 === null
        ? "사업수지는 임대율 100%(완전임대)를 기준으로 잡는다."
        : `사업수지는 임대율 100%(완전임대) 기준이며, 본PF 상환 한계 임대율은 ` +
          `${소수(한계, 1)}% (공실률 ${소수(100 - 한계, 1)}%까지 견딘다).`,
  });
}

/**
 * R-ONE 순영업소득 "천원/㎡" 의 기간 기준을 연으로 바꾸는 배수.
 *
 * [확인 필요] 공식 문서에 기간 기준(월/분기)이 없다. 정황상 분기(3개월) 누적일
 * 가능성이 높아 ×4 로 연환산한다. 확인되는 즉시 이 상수와 라벨을 함께 고칠 것.
 */
export const 순영업소득_연환산배수 = 4;

/**
 * 시장 순영업소득(천원/㎡)을 앱 단위(억원/년)로 환산한다.
 *
 *   X 천원/㎡ × 4(분기→연, 추정) × 연면적(㎡) × 1,000원 ÷ 1억 = 억원/년
 *   = X × 4 × 면적㎡ ÷ 100,000
 *
 * [확인 필요] 분모 면적이 임대(공급)면적인지 연면적인지도 확정되지 않았다.
 * 앱이 가진 임대(공급)면적을 쓰고 화면에 그렇게 밝힌다.
 */
export function 시장NOI를억원연으로(
  값: number | null,
  단위: string,
  공급면적평: number,
): { 값: number | null; 추정: boolean; 원단위: string } {
  if (값 === null) return { 값: null, 추정: false, 원단위: 단위 };
  const u = 단위.split(" ").join("");
  const 면적당 = u.includes("천원") && (u.includes("㎡") || u.includes("m2"));
  if (!면적당) return { 값: null, 추정: false, 원단위: 단위 };
  const 면적m2 = 공급면적평 * 제곱미터_평;
  if (면적m2 <= 0) return { 값: null, 추정: false, 원단위: 단위 };
  return {
    값: (값 * 순영업소득_연환산배수 * 면적m2) / 100_000,
    추정: true,
    원단위: 단위,
  };
}

/** 3) 인근 오피스 순영업소득 vs 앱 자체 계산 NOI */
export function 순영업소득비교표(
  입력: 사업계획입력,
  지표: 시장지표응답 | null,
  강조임계 = 기본강조임계,
): 비교행 {
  const 계획 = 계획값들(입력);
  const 시장단위 = 지표?.단위 ?? "";
  const 원값 = 지표?.값 ?? null;

  // 이미 억원으로 오면 그대로, 천원/㎡ 면 분기 누적으로 가정하고 연환산한다
  const 억원그대로 = 시장단위.includes("억원");
  const 환산 = 억원그대로
    ? { 값: 원값, 추정: false, 원단위: 시장단위 }
    : 시장NOI를억원연으로(원값, 시장단위, 계획.공급면적평);
  const 환산실패 = 원값 !== null && 환산.값 === null;

  const 원값표기 =
    원값 === null
      ? ""
      : `원자료 ${소수(원값)}${시장단위} (기간 기준 확인 중 — 분기 누적 추정)`;

  return 비교행만들기({
    항목: 환산.추정
      ? "순영업소득 (NOI, 연 환산 — 추정)"
      : "순영업소득 (NOI)",
    시장값: 환산실패 ? 원값 : 환산.값,
    시장라벨: 환산실패 ? 시장단위 : "억원/년",
    계획값: 계획.NOI억원,
    계획라벨: "억원/년",
    단위: 환산실패 ? "" : "억원",
    강조임계,
    단위불일치: 환산실패,
    문장꼬리: 환산.추정
      ? `${원값표기} 를 ×${순영업소득_연환산배수} 로 연환산하고 임대(공급)면적 ` +
        `${소수(계획.공급면적평, 0)}평으로 곱해 억원/년으로 맞췄다. ` +
        "[확인 필요] 기간 기준(월/분기)과 면적 기준이 공식 문서로 확정되지 않았다 — 모두 추정이다."
      : 환산실패
        ? `[확인 필요] 시장 단위 "${시장단위}" 에 대한 환산 규칙이 없다. 값만 나란히 싣는다.`
        : "",
  });
}

