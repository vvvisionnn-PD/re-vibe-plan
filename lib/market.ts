/**
 * 차트는 숫자를 다시 계산하지 않는다. 그리기에 필요한 값은 전부 여기서 만들어
 * 넘긴다 — 화면과 검산이 같은 숫자를 쓰게 하려는 것이다.
 */

/** 실거래 건별 평당 매매가 (만원/평) */
export function 평당매매가목록(건: 실거래건[]): number[] {
  return 건
    .map((b) => {
      const 평 = b.건물면적m2 / 제곱미터_평;
      return 평 > 0 ? b.거래금액만원 / 평 : null;
    })
    .filter((v): v is number => v !== null && Number.isFinite(v));
}

export interface 평당가여유 {
  /** 시장 점 분포 — 실거래 건별 평당가 (만원/평) */
  시장점: number[];
  /** 시장 중앙값 (만원/평) */
  시장중앙값: number | null;
  /** 계획 평당가 — 앱 자산가치 ÷ 임대(공급)면적 (만원/평) */
  계획평당: number | null;
  /**
   * 상환 한계 평당가 (만원/평).
   * 본PF 상환 후 잔액이 0 이 되는 자산가치를 평당으로 나눈 값이다.
   *   자산가치 = (본PF + 금융비용) ÷ (1 − 매각수수료율)
   * 이 선 아래로 떨어지면 본PF 원리금을 못 갚는다.
   */
  한계평당: number | null;
  /** 계획 − 한계 (만원/평). 양수면 여유 */
  여유: number | null;
  건수: number;
}

/** 시장 대비 여유 차트에 필요한 값 */
export function 평당가여유계산(
  입력: 사업계획입력,
  실거래: 실거래응답 | null,
): 평당가여유 {
  const 계획 = 계획값들(입력);
  const 평 = 계획.공급면적평;
  const 시장점 = 실거래 ? 평당매매가목록(실거래.건) : [];

  const 계획평당 =
    계획.자산가치억원 !== null && 평 > 0
      ? (계획.자산가치억원 * 10_000) / 평
      : null;

  const 상환의무 = 수(입력.본PF) + 수(입력.본PF금융비용);
  const 잔존비율 = 1 - 배율(입력.매각수수료율);
  const 한계평당 =
    평 > 0 && 잔존비율 > 0 ? ((상환의무 / 잔존비율) * 10_000) / 평 : null;

  return {
    시장점,
    시장중앙값: 평당매매가중앙값(실거래?.건 ?? []),
    계획평당,
    한계평당,
    여유:
      계획평당 !== null && 한계평당 !== null ? 계획평당 - 한계평당 : null,
    건수: 시장점.length,
  };
}

export type 폭포종류 = "시작" | "증가" | "감소" | "합계";

export interface 폭포단계 {
  이름: string;
  /** 증감액 (억원). 감소는 음수 */
  값: number;
  종류: 폭포종류;
  /** 막대 아래끝 (억원) */
  누적시작: number;
  /** 막대 위끝 (억원) */
  누적끝: number;
}

/**
 * 사업수지 폭포 — 연임대수입에서 NOI 까지.
 *
 *   NOI = 임대수입 − 대손충당금 − 운영경비 − 고정비 + 기타수입
 *
 * 덧셈이라 순서를 바꿔도 합은 같다. 사양의 순서
 * (수입 → 변동비 → 고정비 → 기타유입 → 결과)를 그대로 따른다.
 *
 * 다만 대손충당금은 **임대수입 + 기타수입 합계**를 기준으로 산정된다.
 * 막대 순서상 기타수입이 뒤에 오지만 대손 계산에는 이미 포함돼 있다 — 화면에 밝힌다.
 */
export function 수지폭포단계(입력: 사업계획입력): 폭포단계[] {
  const { noi } = 사업성계산(입력, 1);
  const 증감: { 이름: string; 값: number; 종류: 폭포종류 }[] = [
    { 이름: "연임대수입", 값: noi.임대수입, 종류: "시작" },
    { 이름: "대손충당금", 값: -noi.대손충당금, 종류: "감소" },
    { 이름: "운영경비", 값: -noi.운영경비, 종류: "감소" },
    { 이름: "고정비", 값: -noi.고정비, 종류: "감소" },
    { 이름: "기타수입", 값: noi.기타수입, 종류: "증가" },
  ];

  const 단계: 폭포단계[] = [];
  let 누적 = 0;
  for (const s of 증감) {
    const 시작 = s.종류 === "시작" ? 0 : 누적;
    누적 += s.값;
    단계.push({ ...s, 누적시작: Math.min(시작, 누적), 누적끝: Math.max(시작, 누적) });
  }
  단계.push({
    이름: "NOI",
    값: 누적,
    종류: "합계",
    누적시작: Math.min(0, 누적),
    누적끝: Math.max(0, 누적),
  });
  return 단계;
}
