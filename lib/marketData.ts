/**
 * 공공데이터 연동 자리.
 *
 * 지금은 API 를 호출하지 않는다. 화면에서 사용자가 손으로 넣은 시장 기준치를
 * 그대로 돌려주는 더미 구현이며, 인증키가 발급되면 이 파일만 교체하면 되도록
 * 함수 시그니처와 타입을 먼저 고정해 둔다.
 *
 * ※ 인증키는 코드에 하드코딩하지 않는다. 나중에 `.env.local` 에 넣고
 *   서버(Route Handler / Server Action)에서만 읽는다. 이 모듈이 실제 호출을
 *   하게 되는 시점에는 파일 최상단에 `import "server-only"` 를 추가할 것.
 *
 * 참고 통계 목록(추후 연동 대상)
 *   1) 한국부동산원 상업용부동산 임대동향조사
 *      — 분기별·지역별 오피스 임대료 / 공실률 / 투자수익률
 *   2) 서울특별시 오피스빌딩 임대료·공실률 및 수익률 통계
 *
 * ── [확인 필요] R-ONE 순영업소득(오피스) 단위 "천원/㎡" 의 기간 기준 ──
 *
 * 공식 문서에 월 기준인지 분기 기준인지가 **없다.** 정황상 분기(3개월) 누적일
 * 가능성이 높다. 강남 권역 실측으로 대조해 보면:
 *   78.91 천원/㎡ × 4 × 47,272㎡ ÷ 100,000 ≈ 149억원/년
 * 으로 앱이 같은 입력에서 계산한 NOI(약 138억원/년)와 같은 자릿수다.
 * 다만 이는 정황 근거일 뿐 확정이 아니다. 확정 전까지 지킬 것:
 *
 *  1. 화면에는 원자료를 "OO천원/㎡ (기간 기준 확인 중 — 분기 누적 추정)" 으로 적는다.
 *  2. 앱 NOI(연간)와 견줄 때는 분기 기준으로 가정하고 ×4 한다.
 *     → `lib/market.ts` 의 `순영업소득_연환산배수` · `시장NOI를억원연으로()`
 *  3. 그 가정을 화면에 **"(추정)" 라벨로 반드시 노출**한다.
 *  4. 분모 면적이 임대(공급)면적인지 연면적인지도 확정되지 않았다. 앱은 임대(공급)면적을 쓴다.
 *
 * 확인되는 즉시 이 주석과 `순영업소득_연환산배수` 를 함께 고칠 것.
 *
 * [확인 필요] 위 통계의 "소득수익률"이 사업성 검토에서 쓰는 거래사례 기반
 * 캡레이트와 동일한 개념인지는 확인되지 않았다. 소득수익률은 보유기간 중
 * 순영업소득을 자산가액으로 나눈 값으로 공표되지만, 자산가액 산정 기준과
 * 표본이 거래사례 캡레이트와 다를 수 있다. 따라서 화면에서는 캡레이트로
 * 자동 대체하지 않고 "참고용 소득수익률"로 구분해 표기한다.
 */

/**
 * 시장 기준치.
 * 값을 아직 확보하지 못한 항목은 0 이 아니라 `null` 로 둔다.
 * 0 으로 두면 "공실률 0%" 같은 근거 없는 확정 사실이 되어 버린다.
 */
export interface MarketBenchmark {
  /** 통계가 가리키는 지역명 (예: "서울 도심권") */
  지역명: string;
  /** 기준 분기 (예: "2025년 2분기") */
  기준분기: string;
  /** 평당 월임대료 (만원/평/월, 공급면적 기준) */
  평당임대료: number | null;
  /** 공실률 (%) */
  공실률: number | null;
  /** 참고용 소득수익률 (%) — 캡레이트와 같은 개념인지 확인되지 않음 */
  소득수익률: number | null;
  /** 출처명 (통계 제공기관·조사명). 이 값 없이 수치만 표시하지 말 것. */
  출처명: string;
}

/** 아무것도 확보하지 못한 상태. 화면은 이 상태를 "자료 없음"으로 표시한다. */
export const 빈시장기준치: MarketBenchmark = {
  지역명: "",
  기준분기: "",
  평당임대료: null,
  공실률: null,
  소득수익률: null,
  출처명: "",
};

/** 값이 없을 때 화면에 공통으로 쓰는 문구 */
export const 자료없음문구 = "자료 없음 — 공공데이터포털 확인 필요";

/**
 * 지역의 시장 기준치를 가져온다.
 *
 * TODO: 인증키 발급 후 공공데이터포털 API 호출로 교체.
 *       (한국부동산원 상업용부동산 임대동향조사 / 서울시 오피스 통계)
 *       호출은 서버에서만 하고, 응답은 스키마 검증 후 MarketBenchmark 로 변환한다.
 *
 * 현재 구현체는 API 를 타지 않고 화면에서 손으로 넣은 값을 그대로 돌려준다.
 * `region` 은 아직 조회에 쓰이지 않지만, 교체 시 시그니처가 바뀌지 않도록
 * 지금부터 받아 둔다. 수동 입력에 지역명이 비어 있으면 `region` 으로 채운다.
 *
 * @param region 사업대상지 전체 이름 (예: "서울특별시 강남구")
 * @param 수동입력 화면에서 사용자가 직접 넣은 값 (API 연동 전까지의 입력원)
 */
export function getMarketBenchmark(
  region: string,
  수동입력: Partial<MarketBenchmark> = {},
): MarketBenchmark {
  return {
    ...빈시장기준치,
    ...수동입력,
    지역명: (수동입력.지역명 ?? "").trim() || region.trim(),
  };
}

/**
 * 표시 가능한 수치가 하나라도 있는지.
 * 출처명이 없으면 수치가 있어도 단독 표시하지 않는다 —
 * 출처·기준분기 없는 시장 수치는 근거 없는 확정 사실이 되기 때문이다.
 */
export function 시장기준치표시가능(b: MarketBenchmark): boolean {
  const 수치있음 =
    b.평당임대료 !== null || b.공실률 !== null || b.소득수익률 !== null;
  return 수치있음 && b.출처명.trim() !== "" && b.기준분기.trim() !== "";
}
