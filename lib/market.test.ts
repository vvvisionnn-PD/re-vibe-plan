describe("평당 매매가 중앙값", () => {
  const 건 = (금액만원: number, 면적m2: number): 실거래건 => ({
    시군구: "", 법정동: "", 지번: "", 건물유형: "", 건물주용도: "업무시설",
    용도지역: "", 계약일: "2025-01-01", 거래금액만원: 금액만원,
    건물면적m2: 면적m2, 대지면적m2: null, 층: "", 건축년도: "", 거래유형: "",
  });

  it("평당 환산은 400/121 ㎡ 기준이다", () => {
    const 평 = 100 / 제곱미터_평;
    assert.ok(
      Math.abs(평당매매가중앙값([건(10000, 100)])! - 10000 / 평) < 1e-9,
    );
  });

  it("홀수 개는 가운데 값", () => {
    const v = 평당매매가중앙값([건(100, 10), 건(300, 10), 건(200, 10)]);
    assert.ok(Math.abs(v! - 평당매매가중앙값([건(200, 10)])!) < 1e-9);
  });

  it("짝수 개는 가운데 둘의 평균", () => {
    const v = 평당매매가중앙값([건(100, 10), 건(200, 10)]);
    const 기대 = (평당매매가중앙값([건(100, 10)])! + 평당매매가중앙값([건(200, 10)])!) / 2;
    assert.ok(Math.abs(v! - 기대) < 1e-9);
  });

  it("건이 없거나 면적이 0 이면 null", () => {
    assert.equal(평당매매가중앙값([]), null);
    assert.equal(평당매매가중앙값([건(100, 0)]), null);
  });
});

